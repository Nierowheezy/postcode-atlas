/**
 * Ask Atlas evaluation cases (build-plan features 13 and 23).
 *
 * The labelled query battery the benchmark runs in the browser. Each case is
 * data: the text (or turns), the expected answer shape in plain words, and the
 * check functions that score the reply. The checks live in `checks.mjs`.
 *
 * Two fields are metadata for the report, not assertions:
 *
 *   group       the reporting bucket: 'core', 'languages', 'regional-terms',
 *               'ambiguity', or 'tool-accuracy'
 *   expectTool  the Atlas tool the case intends to exercise, or 'none' when no
 *               tool should run (a greeting, an out-of-scope question). The
 *               model picks tools, so this is recorded and read, never used to
 *               fail a case.
 *
 * `expect` is for the report reader; it is not machine-parsed.
 */

